const key = (value: string) => value.trim().toLocaleLowerCase('en')

export function categoryArtPath(category: string | null | undefined, subcategory?: string | null): string | null {
  if (!category) return null
  const parent = key(category)
  const child = subcategory ? SUBCATEGORIES[parent]?.[key(subcategory)] : undefined
  const path = child ?? TOP_LEVEL[parent]
  return path ? `/store-assets/category-art/${path}` : null
}
